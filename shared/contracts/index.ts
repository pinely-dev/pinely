import { getAddress } from "viem";
import type { Address } from "../types";
import { addresses } from "./addresses";
import { deployments } from "./deployments";
import { externalAddresses } from "./external";

export * from "./abis";
export { addresses, deployments, externalAddresses };

export interface PinelyPoolKey {
  currency0: Address;
  currency1: Address;
  fee: number;
  tickSpacing: number;
  hooks: Address;
}

function isAddress(value: string | undefined): value is Address {
  return typeof value === "string" && /^0x[0-9a-fA-F]{40}$/.test(value);
}

/**
 * Returns the address of a contract on a given chain, or undefined when it is not deployed there.
 *
 * Looks in two sources:
 * 1. `addresses.ts`: generated by `scripts/sync-contracts.mjs` from Foundry broadcasts;
 * 2. `external.ts`: third-party addresses (STABLECOIN, EntryPoint, Safe, ...) maintained manually.
 *
 * There is no fallback between names or chains. A missing address is reported as undefined so that
 * callers can fail closed.
 */
export function findContractAddress(
  chainId: number | undefined,
  name: string,
): Address | undefined {
  if (chainId === undefined) return undefined;
  const key = String(chainId);
  const deployed = (addresses as Record<string, Record<string, string> | undefined>)[key]?.[name];
  if (isAddress(deployed)) return deployed;
  const external = (externalAddresses as Record<string, Record<string, string> | undefined>)[key]?.[
    name
  ];
  if (isAddress(external)) return external;
  if (name === "STABLECOIN") {
    const mock = (addresses as Record<string, Record<string, string> | undefined>)[key]?.[
      "MockUSDG"
    ];
    if (isAddress(mock)) return mock;
  }
  return undefined;
}

/**
 * Name of the contract at `address` on a chain, from the address books, or undefined when it is not listed.
 * Used to tell a user which contract a transaction calls; an unlisted address is never given a name.
 */
export function findContractName(chainId: number | undefined, address: string): string | undefined {
  if (chainId === undefined) return undefined;
  const key = String(chainId);
  const target = address.toLowerCase();
  const books = [addresses, externalAddresses] as Array<
    Record<string, Record<string, string> | undefined>
  >;
  for (const book of books) {
    const entries = book[key];
    if (!entries) continue;
    for (const [name, value] of Object.entries(entries)) {
      if (typeof value === "string" && value.toLowerCase() === target) return name;
    }
  }
  return undefined;
}

/**
 * Hash of the transaction that deployed a contract on a chain, from the committed Foundry broadcasts
 * (`deployments.ts`, generated by `scripts/sync-contracts.mjs`). Undefined when it is not known.
 */
export function findDeployTx(chainId: number | undefined, name: string): string | undefined {
  if (chainId === undefined) return undefined;
  const entry = (
    deployments as Record<string, Record<string, { address: string; txHash: string }> | undefined>
  )[String(chainId)]?.[name];
  return entry && /^0x[0-9a-fA-F]{64}$/.test(entry.txHash) ? entry.txHash : undefined;
}

/** Contract address (CA) of the $PINELY token on a chain: not launched yet, or the official address. */
export type PinelyTokenCa = { status: "tba" } | { status: "live"; address: Address };

/**
 * Resolves the official $PINELY token CA for a chain from `external.ts` (key `PINELY`).
 *
 * An unset key is "TBA", never a guess. A set key must be a non-zero address in exact EIP-55
 * checksum form; anything else throws, so a mistyped or lowercased address fails the build instead
 * of being shown to users as the official token.
 */
export function resolvePinelyTokenCa(
  chainId: number | undefined,
  source: Record<string, Record<string, string> | undefined> = externalAddresses,
): PinelyTokenCa {
  if (chainId === undefined) return { status: "tba" };
  const raw = source[String(chainId)]?.PINELY;
  if (raw === undefined || raw === "") return { status: "tba" };

  if (!isAddress(raw) || /^0x0{40}$/.test(raw) || getAddress(raw) !== raw) {
    throw new Error(
      `[PINELY] shared/contracts/external.ts: PINELY on chain ${chainId} must be a non-zero address ` +
        `in exact EIP-55 checksum form (got "${raw}").`,
    );
  }
  return { status: "live", address: raw };
}

/**
 * Like `findContractAddress`, but throws when the address is missing.
 * Mandatory on mainnet paths so misconfiguration fails hard (fail-closed) instead of silently
 * falling back to a dummy address.
 */
export function requireContractAddress(chainId: number | undefined, name: string): Address {
  const found = findContractAddress(chainId, name);
  if (!found) {
    throw new Error(
      `[PINELY] SSOT address for "${name}" not found on chain ${chainId}. ` +
        `Populate shared/contracts/external.ts (external address) or run deploy + sync first.`,
    );
  }
  return found;
}

/**
 * Builds the canonical Uniswap v4 PoolKey for a PINELY machine pool.
 * Machine pools use a dynamic fee (0x800000) and the PinelyHook.
 */
export function getPinelyPoolKey(
  chainId: number,
  tokenInAddress: Address,
  settlementAddress?: Address,
): PinelyPoolKey | undefined {
  const hookAddress = findContractAddress(chainId, "PinelyHook");
  const targetSettlement = settlementAddress ?? findContractAddress(chainId, "STABLECOIN");
  if (!hookAddress || !targetSettlement) return undefined;

  const [currency0, currency1] =
    tokenInAddress.toLowerCase() < targetSettlement.toLowerCase()
      ? [tokenInAddress, targetSettlement]
      : [targetSettlement, tokenInAddress];

  return {
    currency0,
    currency1,
    fee: 0x800000, // DYNAMIC_FEE_FLAG
    tickSpacing: 60,
    hooks: hookAddress,
  };
}
