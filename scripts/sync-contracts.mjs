import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { supportedChains } from "../shared/chains/index.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contractsDir = join(root, "contracts");
const outDir = join(root, "shared", "contracts");

/** Only the supported chains (shared/chains) are ever written to the address book. */
const SUPPORTED_CHAIN_IDS = new Set(supportedChains.map((chain) => String(chain.id)));

const defaultContracts = [
  "BurnVault",
  "CreatorFeeSplitter",
  "FleetSubscription",
  "MachineRegistry",
  "MockPinelyToken",
  "MockUSDG",
  "PinelyAccount",
  "PinelyAccountFactory",
  "PinelyHook",
  "PinelyPaymaster",
  "PinelyRouter",
  "PinelyStake",
  "PoolSeeder",
  "SurplusSweeper",
];
const explicitNames = process.argv.slice(2);
const names = explicitNames.length > 0 ? explicitNames : defaultContracts;

function walkFiles(dir) {
  if (!existsSync(dir)) return [];
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walkFiles(full));
    else if (entry.isFile()) files.push(full);
  }
  return files;
}

/**
 * Foundry writes artifacts to out/<File>.sol/<Contract>.json. Files compiled with several solc
 * versions use out/<File>.sol/<Contract>.<solc>.json (for example PoolSeeder, pragma ^0.8.26).
 * Prefer the exact match, then fall back to the highest versioned variant (the ABI is identical).
 */
function findArtifact(name) {
  const artifactRoot = join(contractsDir, "out");
  const candidates = walkFiles(artifactRoot).filter(
    (file) =>
      basename(dirname(file)) === `${name}.sol` &&
      (basename(file) === `${name}.json` ||
        (basename(file).startsWith(`${name}.`) && basename(file).endsWith(".json"))),
  );
  if (candidates.length === 0) return undefined;
  candidates.sort((a, b) => {
    const aExact = basename(a) === `${name}.json` ? 0 : 1;
    const bExact = basename(b) === `${name}.json` ? 0 : 1;
    if (aExact !== bExact) return aExact - bExact;
    return b.localeCompare(a);
  });
  return candidates[0];
}

function readArtifactAbi(file) {
  const artifact = JSON.parse(readFileSync(file, "utf8"));
  if (!Array.isArray(artifact.abi)) {
    throw new Error(`Artifact does not contain an abi field: ${file}`);
  }
  return artifact.abi;
}

// 1) ABI -> shared/contracts/abis/<Name>.ts
const abisDir = join(outDir, "abis");
mkdirSync(abisDir, { recursive: true });

const written = new Set();
for (const name of names) {
  const artifact = findArtifact(name);
  if (!artifact) {
    if (explicitNames.length > 0) {
      console.error(
        `Artifact not found for ${name}.\n` +
          `Run \`forge build\` (or \`bun run contracts:build\`) first.`,
      );
      process.exit(1);
    }
    console.warn(`[sync] No artifact for ${name}; run \`forge build\` first. Skipping.`);
    continue;
  }

  const abi = readArtifactAbi(artifact);
  const varName = name[0].toLowerCase() + name.slice(1) + "Abi";
  writeFileSync(
    join(abisDir, `${name}.ts`),
    `// This file is auto-generated by scripts/sync-contracts.mjs - do not edit manually.\nexport const ${varName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  written.add(name);
}

// A full sync removes ABI files of contracts that no longer exist.
if (explicitNames.length === 0) {
  for (const file of readdirSync(abisDir)) {
    if (!file.endsWith(".ts") || file === "index.ts") continue;
    if (!defaultContracts.includes(file.replace(/\.ts$/, ""))) {
      rmSync(join(abisDir, file));
      console.log(`[sync] Removed stale ABI: ${file}`);
    }
  }
}

const abiFiles = readdirSync(abisDir)
  .filter((file) => file.endsWith(".ts") && file !== "index.ts" && !file.endsWith(".d.ts"))
  .map((file) => file.replace(/\.ts$/, ""))
  .sort();

writeFileSync(
  join(abisDir, "index.ts"),
  "// This file is auto-generated by scripts/sync-contracts.mjs - do not edit manually.\n" +
    abiFiles.map((file) => `export * from "./${file}";`).join("\n") +
    "\n",
);

// 2) Addresses -> shared/contracts/addresses.ts
const addresses = {};
// Deploy transaction of each contract (from the same broadcasts) -> shared/contracts/deployments.ts
const deployments = {};

function setAddress(chainId, name, address) {
  if (!SUPPORTED_CHAIN_IDS.has(String(chainId))) return;
  if (!address || typeof address !== "string") return;
  addresses[chainId] ??= {};
  addresses[chainId][name] = address;
}

// Keep previously recorded addresses of the supported chains (never legacy or local chains).
const existingAddressesPath = join(outDir, "addresses.ts");
if (existsSync(existingAddressesPath)) {
  const content = readFileSync(existingAddressesPath, "utf8");
  const match = content.match(/export const addresses = (\{[\s\S]*\}) as const;/);
  if (match) {
    try {
      const parsed = JSON.parse(match[1]);
      for (const [chainId, map] of Object.entries(parsed)) {
        for (const [name, addr] of Object.entries(map)) {
          setAddress(chainId, name, addr);
        }
      }
    } catch (error) {
      console.warn(
        "[sync] Could not parse the existing addresses.ts; starting from broadcasts only.",
        error,
      );
    }
  }
}

// Primary source: Foundry broadcast/<Script>.s.sol/<chainId>/run-latest.json.
const broadcastDir = join(contractsDir, "broadcast");
if (existsSync(broadcastDir)) {
  for (const scriptDir of readdirSync(broadcastDir, { withFileTypes: true })) {
    if (!scriptDir.isDirectory()) continue;
    const scriptPath = join(broadcastDir, scriptDir.name);
    for (const chainDir of readdirSync(scriptPath, { withFileTypes: true })) {
      if (!chainDir.isDirectory() || !/^\d+$/.test(chainDir.name)) continue;
      if (!SUPPORTED_CHAIN_IDS.has(chainDir.name)) {
        console.warn(
          `[sync] Ignoring broadcast for unsupported chain ${chainDir.name} (${scriptDir.name}).`,
        );
        continue;
      }

      const chainPath = join(scriptPath, chainDir.name);
      const latest = join(chainPath, "run-latest.json");
      let runFile = existsSync(latest) ? latest : undefined;
      if (!runFile) {
        const runs = readdirSync(chainPath)
          .filter((file) => /^run-\d+\.json$/.test(file))
          .sort(
            (a, b) => statSync(join(chainPath, b)).mtimeMs - statSync(join(chainPath, a)).mtimeMs,
          );
        if (runs[0]) runFile = join(chainPath, runs[0]);
      }
      if (!runFile) continue;

      const run = JSON.parse(readFileSync(runFile, "utf8"));
      for (const tx of run.transactions ?? []) {
        if (tx.transactionType !== "CREATE" && tx.transactionType !== "CREATE2") continue;
        if (tx.contractName && tx.contractAddress) {
          setAddress(chainDir.name, tx.contractName, tx.contractAddress);
          if (tx.hash) {
            deployments[chainDir.name] ??= {};
            deployments[chainDir.name][tx.contractName] = {
              address: tx.contractAddress,
              txHash: tx.hash,
            };
          }
          if (tx.contractName === "MockUSDG") {
            setAddress(chainDir.name, "STABLECOIN", tx.contractAddress);
          }
        }
      }
    }
  }
}

writeFileSync(
  join(outDir, "addresses.ts"),
  `// This file is auto-generated by scripts/sync-contracts.mjs - do not edit manually.\nexport const addresses = ${JSON.stringify(addresses, null, 2)} as const;\n`,
);

writeFileSync(
  join(outDir, "deployments.ts"),
  `// This file is auto-generated by scripts/sync-contracts.mjs - do not edit manually.\nexport const deployments = ${JSON.stringify(deployments, null, 2)} as const;\n`,
);

console.log("Contract sync completed:", { abi: abiFiles, chains: Object.keys(addresses) });
console.log(
  "Note: EXTERNAL addresses (STABLECOIN, PoolManager, EntryPoint, $PINELY, Safe) are maintained " +
    "manually in shared/contracts/external.ts and never overwritten by sync. Take them only from " +
    "the official Robinhood Chain documentation.",
);
